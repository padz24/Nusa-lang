// Nusa → header C — implementasi milestone 1 (Phase 110).
// Hanya frontend Nusa (lex/parse/AST) + string; tanpa LLVM.
// Subset jujur (ABI §abi-3.10): i64/string/void + struct/enum datar
// tanpa bool; sisanya skip + warning. `bool` DITOLAK eksplisit
// (i1 internal vs `_Bool` C = mismatch biner, bukan opini gaya).
#include "compiler/bindgen/Headers.h"

#include "compiler/ast/AST.h"
#include "compiler/diagnostics/Diagnostic.h"
#include "compiler/lexer/Lexer.h"
#include "compiler/parser/Parser.h"

